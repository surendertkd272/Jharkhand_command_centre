// Scan /public/avatars for real raster photos and write lib/avatarManifest.ts.
// Drop photos named <name-slug>.jpg|jpeg|png|webp into public/avatars/, then:
//   node scripts/gen-avatar-manifest.mjs
// The <Avatar> component will prefer a real photo when the manifest lists it,
// otherwise it uses the generated <slug>.svg, otherwise a tinted initials chip.
import { readdirSync, writeFileSync } from "node:fs";

const DIR = "public/avatars";
const RASTER = /\.(jpe?g|png|webp)$/i;

const map = {};
for (const f of readdirSync(DIR)) {
  if (!RASTER.test(f)) continue;
  const dot = f.lastIndexOf(".");
  map[f.slice(0, dot)] = f.slice(dot + 1).toLowerCase();
}

const body =
  "// Auto-generated by scripts/gen-avatar-manifest.mjs — do not edit by hand.\n" +
  "// Maps an athlete name-slug -> the raster photo extension present in\n" +
  "// /public/avatars. Regenerate:  node scripts/gen-avatar-manifest.mjs\n" +
  "export const AVATAR_PHOTOS: Record<string, string> = " +
  JSON.stringify(map, null, 2) +
  ";\n";

writeFileSync("lib/avatarManifest.ts", body);
console.log(`avatar manifest: ${Object.keys(map).length} real photo(s) detected`);
